"""Nav2 for the warehouse Husky, with a separate map for localization and for planning.

The racks are open frames: the lidar looks between the shelves and sees only their posts, but the
robot cannot drive under them. So:
  * AMCL localizes on the scan map  (maps/our_structured_warehouse_map_scan.yaml: what the lidar sees)
  * the costmaps plan on the solid map  (maps/our_structured_warehouse_map.yaml: racks as obstacles)
Both are generated by scripts/generate_occupancy_grid.py.

Usage (inside the container, with the Husky simulation running):
  ros2 launch warehouse_husky nav2.launch.py
"""
import os

from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, IncludeLaunchDescription
from launch.launch_description_sources import PythonLaunchDescriptionSource
from launch.substitutions import LaunchConfiguration, PathJoinSubstitution
from launch_ros.actions import Node


def generate_launch_description():
    pkg_share = get_package_share_directory('warehouse_husky')
    nav2_launch = os.path.join(get_package_share_directory('nav2_bringup'), 'launch', 'bringup_launch.py')

    scan_map = LaunchConfiguration('scan_map')
    nav_map = LaunchConfiguration('nav_map')

    nav2 = IncludeLaunchDescription(
        PythonLaunchDescriptionSource(nav2_launch),
        launch_arguments={
            'map': scan_map,  # map_server + AMCL
            'params_file': os.path.join(pkg_share, 'config', 'nav2_params.yaml'),
            'use_sim_time': 'true',
        }.items(),
    )

    # Second map server for the costmaps, on /map_nav (the static layers in nav2_params.yaml read it)
    nav_map_server = Node(
        package='nav2_map_server',
        executable='map_server',
        name='map_server_nav',
        parameters=[{'yaml_filename': nav_map, 'use_sim_time': True}],
        remappings=[('map', 'map_nav')],
        output='screen',
    )
    nav_map_lifecycle = Node(
        package='nav2_lifecycle_manager',
        executable='lifecycle_manager',
        name='lifecycle_manager_map_nav',
        parameters=[{'node_names': ['map_server_nav'], 'autostart': True, 'use_sim_time': True}],
        output='screen',
    )

    return LaunchDescription([
        DeclareLaunchArgument('scan_map', default_value='/main/maps/our_structured_warehouse_map_scan.yaml',
                              description='Map of what the lidar sees, for AMCL'),
        DeclareLaunchArgument('nav_map', default_value='/main/maps/our_structured_warehouse_map.yaml',
                              description='Map with solid racks, for the costmaps'),
        nav2,
        nav_map_server,
        nav_map_lifecycle,
    ])
