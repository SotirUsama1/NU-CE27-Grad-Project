#!/usr/bin/env python3
"""Builds config/waypoints.yaml: a named, checked place to drive to for everything in the semantic database.

The semantic database (maps/semantic.json, made by the mapping branch's generate_semantic_db.py from
Our_Structured_Warehouse.world) says where every rack, zone, the dock, the truck and every labelled box is.
A robot cannot drive to the middle of a rack, so for each of them this picks the stand-off point:
  * on floor the robot can reach from the home position (a route exists that respects the 0.625 m the
    planner keeps from obstacles),
  * with room all round (0.95 m from any obstacle if possible, else 0.85 m, else 0.75 m),
  * as close to the thing as that allows,
  * facing it.
Run (needs numpy and pyyaml, so inside the container):
  python3 scripts/generate_waypoints.py
"""
import math
import os
import sys

import numpy as np
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
sys.path.insert(0, PKG)
from warehouse_nav.grid import GridMap, reachable_from  # noqa: E402

HOME = (-1.5, 2.0, 0.0)          # an open spot near the start; everything must be reachable from it
PASS_CLEARANCE = 0.625           # the planner's keep-out: half width 0.345 + footprint padding 0.28
CLEARANCES = (0.95, 0.85, 0.75)  # wanted room around a place, best first
MAX_DISTANCE = 3.0               # how far from the thing the stand-off point may be


def norm(name):
    return str(name).strip().lower().replace(' ', '_').replace('-', '_')


def distance_to_rect(px, py, cx, cy, yaw, w, l):
    """Distance from points to a rectangle (centre, yaw, size w along its x and l along its y)."""
    dx, dy = px - cx, py - cy
    lx = math.cos(-yaw) * dx - math.sin(-yaw) * dy
    ly = math.sin(-yaw) * dx + math.cos(-yaw) * dy
    return np.hypot(np.maximum(np.abs(lx) - w / 2, 0), np.maximum(np.abs(ly) - l / 2, 0))


def main():
    db = yaml.safe_load(open(os.path.join(PKG, 'maps', 'semantic.json')))
    gm = GridMap.from_yaml(os.path.join(PKG, 'maps', 'warehouse.yaml'))
    reach = reachable_from(~np.zeros_like(gm.occupied) & gm.clear_of_obstacles(PASS_CLEARANCE), gm.cell(*HOME[:2]))
    ok = {c: reach & gm.clear_of_obstacles(c) for c in CLEARANCES}
    rows_cols = {c: np.nonzero(ok[c]) for c in CLEARANCES}
    xy = {c: gm.xy(*rows_cols[c]) for c in CLEARANCES}

    entries = {}
    skipped = []

    def add(name, kind, cx, cy, yaw, w, l, rect=True, info=''):
        for c in CLEARANCES:
            xs, ys = xy[c]
            d = distance_to_rect(xs, ys, cx, cy, yaw, w, l) if rect else np.hypot(xs - cx, ys - cy)
            near = np.nonzero(d <= MAX_DISTANCE)[0]
            if len(near) == 0:
                continue
            k = near[np.argmin(d[near])]
            entries[norm(name)] = {
                'x': round(float(xs[k]), 2), 'y': round(float(ys[k]), 2),
                'yaw': round(math.atan2(cy - ys[k], cx - xs[k]), 2),
                'kind': kind, 'clearance': c, 'distance_to_target': round(float(d[k]), 2),
                'description': info or name}
            return
        skipped.append(name)

    for name, e in db.items():
        t, p = e.get('model_type', ''), e['position']
        dim = e.get('physical_dimensions', {})
        w, l, yaw = dim.get('width_x', 0.5), dim.get('length_y', 0.5), e.get('rotation_yaw', 0.0)
        if t.startswith('warehouse_rack'):
            add(name, 'rack', p['x'], p['y'], yaw, w, l, info=f'rack {name.split("_", 1)[1]}')
        elif t == 'labeled_box':
            add('box_' + e['label'], 'box', p['x'], p['y'], 0, 0, 0, rect=False, info=f'box {e["label"]}')
        elif t == 'dock_conveyor':
            add('dock', 'dock', p['x'], p['y'], yaw, w, l, info='shipping dock conveyor')
        elif t == 'delivery_truck':
            add('truck', 'dock', p['x'], p['y'], yaw, w, l, info='delivery truck')
        elif name.startswith('zone_') and name.endswith('_layout'):
            z = name.split('_')[1]
            add(f'zone_{z}', 'zone', p['x'], p['y'], 0, 0, 0, rect=False, info=f'centre of zone {z}')

    entries['home'] = {'x': HOME[0], 'y': HOME[1], 'yaw': HOME[2], 'kind': 'home', 'clearance': 0.0,
                       'distance_to_target': 0.0, 'description': 'open floor near the start'}
    out = os.path.join(PKG, 'config', 'waypoints.yaml')
    with open(out, 'w') as f:
        f.write('# Generated by scripts/generate_waypoints.py from maps/semantic.json; do not edit by hand.\n'
                '# Names are lower case; "A-001" style box labels become box_a_001.\n')
        yaml.safe_dump({'places': dict(sorted(entries.items()))}, f, sort_keys=False, default_flow_style=None)
    kinds = {}
    for v in entries.values():
        kinds[v['kind']] = kinds.get(v['kind'], 0) + 1
    print(f'{len(entries)} places written to {out}: {kinds}')
    low = [n for n, v in entries.items() if v['clearance'] and v['clearance'] < 0.95]
    print(f'{len(low)} of them have less than 0.95 m of room; {len(skipped)} have no reachable stand-off point: {skipped[:10]}')


if __name__ == '__main__':
    main()
